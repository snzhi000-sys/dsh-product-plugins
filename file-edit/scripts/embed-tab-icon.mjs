/**
 * Regenerates client/src/tab-icon.js from client/src/assets/sidebar-tab.webp.
 *
 * The plugin factory's `require` resolves through the shell's static module table at runtime, so a
 * binary asset cannot be required: it has to reach the bundle as a string. The generated module is
 * committed, so the bundle stays reproducible without this step.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'

const pluginDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const asset = join(pluginDir, 'client', 'src', 'assets', 'sidebar-tab.webp')
const target = join(pluginDir, 'client', 'src', 'tab-icon.js')

const dataUrl = `data:image/webp;base64,${readFileSync(asset).toString('base64')}`
const source = `// Generated by scripts/embed-tab-icon.mjs from client/src/assets/sidebar-tab.webp.
// The right-sidebar tab chip draws this glyph; the plugin factory's runtime require cannot reach a
// binary asset, so the data URL is bundled as a string instead. Regenerate with: npm run build:icon
/** Data URL of the sidebar tab glyph. */
export const SIDEBAR_TAB_ICON = '${dataUrl}'
`
writeFileSync(target, source)
console.log(`embedded ${String(dataUrl.length)} characters from ${asset.slice(pluginDir.length + 1)}`)
